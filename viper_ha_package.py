    return [
        "- id: viper_vision_door_ai_monitor",
        "  alias: 'Viper Vision: Door AI Monitor'",
        "  description: Sends selected doorbell motion events to Viper Vision.",
        "  mode: single",
        "  triggers:",
        *triggers,
        "  actions:",
        "    - choose:",
        *choices,
    ]


