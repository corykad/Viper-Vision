def get_default_package_options():
    return deepcopy(DEFAULT_PACKAGE_OPTIONS)


def package_options_from_config(config_data=None):
    options = get_default_package_options()
    data = cfg.validate_and_normalize_config(config_data) if config_data is not None else cfg.load_config()
    doorbell = cfg.get_resolved_doorbell_settings(data, include_env=True)
    options["viper_host"] = data.get("viper_host") or cfg.PC_IP
    options["viper_port"] = data.get("flask_port") or cfg.FLASK_PORT
    options["front_doorbell_mqtt_topic"] = doorbell.get("front_doorbell_mqtt_topic", "")
    options["back_doorbell_mqtt_topic"] = doorbell.get("back_doorbell_mqtt_topic", "")
    return options


def package_options_from_discovery(discovery_result, base_options=None):
    """Build conservative package options from discovery results.

    The wizard should let users confirm these guesses before writing a package.
    """
    options = deepcopy(base_options or get_default_package_options())
    if not discovery_result or not discovery_result.get("ok"):
        return options

    categories = discovery_result.get("categories", {})
    options["fridge_door_entity"] = _first_entity_id(categories.get("fridge_sensors", []), "door")
    options["freezer_door_entity"] = _first_entity_id(categories.get("freezer_sensors", []), "door")
    options["filter_sensor_entity"] = _first_entity_id(categories.get("filter_sensors", []))
    options["vacuum_status_entity"] = _first_entity_id(categories.get("roborock_entities", [])) or _first_entity_id(categories.get("vacuum_entities", []))
    ice_candidate = _first_entity_id(categories.get("ice_maker_candidates", []), "switch.") or _first_entity_id(categories.get("ice_maker_candidates", []))
    if ice_candidate:
        options["ice_maker_switch_entity"] = ice_candidate
    return options


def generate_viper_ha_package(options=None):
    """Return a Home Assistant package YAML string for manual installation."""
    opts = _normalize_options(options)
    base_url = f"http://{opts['viper_host']}:{opts['viper_port']}"
    lines = [
        "# Viper Vision Home Assistant package",
        "# Generated by Viper Vision. Review entity IDs before installing.",
        "# Install as /config/packages/viper_vision_package.yaml, then reload YAML or restart Home Assistant.",
        "",
        "rest_command:",
        _rest_command_block("ring_vision_front", f"{base_url}/doorbell-webhook"),
        _rest_command_block("ring_vision_back", f"{base_url}/doorbell-webhook/back"),
        _broadcast_command_block("viper_broadcast", f"{base_url}/remote/broadcast"),
        _broadcast_command_block("viper_broadcast_push", f"{base_url}/remote/broadcast_push"),
        _broadcast_command_block("cinderella_broadcast", f"{base_url}/remote/broadcast"),
        _broadcast_command_block("ha_announce", f"{base_url}/remote/broadcast"),
        _cinderella_command_block(f"{base_url}/cinderella"),
    ]

    helper_lines = _helper_blocks(opts)
    if helper_lines:
        lines.extend(["", *helper_lines])

    automations = []
    if opts["include_doorbell"]:
        automations.extend(_doorbell_automations(opts))
    if opts["include_ice_maker"]:
        automations.extend(_ice_maker_automations(opts))
    if opts["include_fridge"]:
        automations.extend(_fridge_automations(opts))
    if opts["include_filter"]:
        automations.extend(_filter_automations(opts))
    if opts["include_cinderella"]:
        automations.extend(_cinderella_automations(opts))
    if opts["include_cinderella_debug"]:
        automations.extend(_cinderella_debug_automation(opts))

    if automations:
        lines.extend(["", "automation:", *automations])

    return "\n".join(line.rstrip() for line in lines if line is not None).rstrip() + "\n"


def write_viper_ha_package(options=None, output_path=None):
    path = Path(output_path) if output_path else PACKAGE_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    package_text = generate_viper_ha_package(options)
    path.write_text(package_text, encoding="utf-8")
    return path


