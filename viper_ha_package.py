def _fridge_automations(opts):
    fridge = opts["fridge_door_entity"]
    freezer = opts["freezer_door_entity"]
    triggers = []
    choices = []
    if fridge:
        triggers.extend(_state_trigger(fridge, "on", "fridge_open"))
        triggers.extend(_state_trigger(fridge, "off", "fridge_closed"))
        choices.extend(_broadcast_choice("fridge_open", "The fridge door is open.", "fridge_open"))
        choices.extend(_broadcast_choice("fridge_closed", "The fridge door is closed.", "fridge_closed"))
    if freezer:
        triggers.extend(_state_trigger(freezer, "on", "freezer_open"))
        triggers.extend(_state_trigger(freezer, "off", "freezer_closed"))
        choices.extend(_broadcast_choice("freezer_open", "The freezer door is open.", "freezer_open"))
        choices.extend(_broadcast_choice("freezer_closed", "The freezer door is closed.", "freezer_closed"))
    if not triggers:
        return []
    return [
        "- id: viper_refrigerator_door_announcements",
        "  alias: 'Viper Vision: Refrigerator Door Announcements'",
        "  mode: single",
        "  triggers:",
        *triggers,
        "  actions:",
        "    - choose:",
        *choices,
    ]


