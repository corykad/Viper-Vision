def _cinderella_automations(opts):
    status = opts["vacuum_status_entity"]
    vacuum_error = opts["vacuum_error_entity"]
    dock_error = opts["dock_error_entity"]
    drying = opts["dock_mop_drying_entity"]
    triggers = []
    choices = []
    if vacuum_error:
        triggers.extend([
            "    - trigger: state",
            f"      entity_id: {vacuum_error}",
            "      not_to: ['none', 'unknown', 'unavailable']",
            "      id: vacuum_error",
        ])
        choices.extend(_choice_action("vacuum_error", ["            - action: rest_command.cinderella_event", "              data:", "                event: 'error'", f"                error: \"{{{{ states('{vacuum_error}') }}}}\"", "                source: 'vacuum'"]))
    if dock_error:
        triggers.extend([
            "    - trigger: state",
            f"      entity_id: {dock_error}",
            "      not_to: ['ok', 'unknown', 'unavailable']",
            "      id: dock_error",
        ])
        choices.extend(_choice_action("dock_error", ["            - action: rest_command.cinderella_event", "              data:", "                event: 'error'", f"                error: \"{{{{ states('{dock_error}') }}}}\"", "                source: 'dock'"]))
    if status:
        triggers.extend(_multi_to_trigger(status, "['starting', 'cleaning', 'spot_cleaning', 'zoned_cleaning', 'zone_cleaning', 'segment_cleaning', 'mapping', 'patrol', 'robot_status_mopping', 'clean_mop_cleaning', 'clean_mop_mopping', 'segment_mopping', 'segment_clean_mop_cleaning', 'segment_clean_mop_mopping', 'zoned_mopping', 'zoned_clean_mop_cleaning', 'zoned_clean_mop_mopping']", 1, "departure"))
        triggers.extend(_multi_to_trigger(status, "['washing_mop', 'washing_the_mop', 'washing_the_mop_2', 'back_to_dock_washing_duster']", 2, "washing"))
        triggers.extend(_multi_to_trigger(status, "['emptying', 'emptying_bin', 'emptying_dustbin', 'emptying_the_bin']", 2, "emptying"))
        triggers.extend(_multi_to_trigger(status, "['returning', 'returning_home', 'docking', 'going_to_target', 'going_to_wash_the_mop', 'attaching_the_mop', 'detaching_the_mop', 'air_drying_stopping']", 2, "returning"))
        triggers.extend(_multi_to_trigger(status, "['charging', 'docked', 'charging_complete', 'idle']", 2, "victory"))
        triggers.extend(_multi_to_trigger(status, "['paused', 'remote_control_active', 'manual_mode', 'in_call', 'locked']", 2, "paused"))
        triggers.extend(_multi_to_trigger(status, "['unknown', 'charger_disconnected', 'charging_problem', 'error', 'shutting_down', 'updating', 'device_offline', 'egg_attack']", 2, "status_update"))
        for event in ["departure", "washing", "emptying", "returning", "victory", "paused", "status_update"]:
            choices.extend(_choice_action(event, ["            - action: rest_command.cinderella_event", "              data:", f"                event: '{event}'"]))
    if drying:
        triggers.extend(_state_trigger(drying, "on", "drying", seconds=2))
        choices.extend(_choice_action("drying", ["            - action: rest_command.cinderella_event", "              data:", "                event: 'drying'"]))
    if not triggers:
        return []
    return [
        "- id: viper_cinderella_event_router",
        "  alias: 'Viper Vision: Cinderella Event Router'",
        "  mode: queued",
        "  max: 10",
        "  triggers:",
        *triggers,
        "  actions:",
        "    - delay: '00:00:01'",
        "    - choose:",
        *choices,
    ]


def _cinderella_debug_automation(opts):
    entities = [opts[key] for key in ["vacuum_status_entity", "vacuum_error_entity", "dock_error_entity", "dock_mop_drying_entity"] if opts.get(key)]
    if not entities:
        return []
    return [
        "- id: viper_cinderella_debug_log",
        "  alias: 'Viper Vision: Cinderella Debug Log'",
        "  mode: queued",
        "  triggers:",
        "    - trigger: state",
        "      entity_id:",
        *[f"        - {entity}" for entity in entities],
        "  actions:",
        "    - action: system_log.write",
        "      data:",
        "        level: warning",
        "        message: >",
        "          Cinderella change | entity={{ trigger.entity_id }} | from={{ trigger.from_state.state if trigger.from_state else 'none' }} | to={{ trigger.to_state.state if trigger.to_state else 'none' }}",
    ]


def _state_trigger(entity_id, to_state, trigger_id, seconds=None):
    lines = [
        "    - trigger: state",
        f"      entity_id: {entity_id}",
        f"      to: '{to_state}'",
    ]
    if seconds:
        lines.extend(["      for:", f"        seconds: {seconds}"])
    lines.append(f"      id: {trigger_id}")
    return lines


def _multi_to_trigger(entity_id, to_states, seconds, trigger_id):
    return [
        "    - trigger: state",
        f"      entity_id: {entity_id}",
        f"      to: {to_states}",
        "      for:",
        f"        seconds: {seconds}",
        f"      id: {trigger_id}",
    ]


def _broadcast_choice(trigger_id, message, channel):
    return _choice_action(trigger_id, [
        "            - action: rest_command.viper_broadcast",
        "              data:",
        f"                message: {_q(message)}",
        f"                channel: {channel}",
    ])


def _choice_action(trigger_id, action_lines):
    return [
        "        - conditions:",
        "            - condition: trigger",
        f"              id: {trigger_id}",
        "          sequence:",
        *action_lines,
    ]


def _first_entity_id(entities, contains=None):
    for entity in entities or []:
        entity_id = entity.get("entity_id", "")
        text = f"{entity_id} {entity.get('friendly_name', '')}".lower()
        if contains is None or contains.lower() in text:
            return entity_id
    return ""


def _q(value):
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'
